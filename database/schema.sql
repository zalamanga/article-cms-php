CREATE TABLE IF NOT EXISTS admin_users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(100) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL,
 email VARCHAR(254) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS articles (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(255) NOT NULL, slug VARCHAR(255) DEFAULT NULL,
 category VARCHAR(100) NOT NULL DEFAULT '', content LONGTEXT NOT NULL,
 author VARCHAR(150) NOT NULL DEFAULT '', author_name VARCHAR(150) NOT NULL DEFAULT '',
 author_title VARCHAR(150) NOT NULL DEFAULT '', excerpt TEXT DEFAULT NULL,
 featured_image VARCHAR(255) DEFAULT NULL, tags TEXT DEFAULT NULL,
 publish_date DATE DEFAULT NULL, published_date DATE DEFAULT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'draft', views INT UNSIGNED NOT NULL DEFAULT 0,
 reading_time INT NOT NULL DEFAULT 5,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
